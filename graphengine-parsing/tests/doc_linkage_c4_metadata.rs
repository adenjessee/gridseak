//! In-memory external-documentation linkage over GridSeak nodes.
//!
//! # What this proves
//!
//! The compatibility under test is **survival of a linked document inside
//! a node's metadata** — nothing about any external wire format. A
//! documentation reference (a UUID pointing at an external doc —
//! Confluence / Notion / a GitHub `.md`) stored inside a node's
//! `properties` (the node's metadata bag) survives an FQN mutation that
//! churns the node's content-addressed `id`. Every survival assertion
//! inspects `node.properties` **directly** (see
//! [`assert_doc_link_in_metadata`]) so the proof is that the link
//! physically resides in the node metadata, not merely that a helper
//! returned it. It proves this for a single node and for a deeply nested
//! child inside a C4-style model of an online ordering / delivery system
//! (L1 System → L2 Container → L3 Component → L4 Code).
//!
//! NodeSync compatibility is explicitly **not** a goal here — that layer
//! is being rebuilt. The in-memory [`DocsStore`] is only a stand-in so a
//! surviving UUID can be shown to still resolve to a real doc.
//!
//! # Why the link survives
//!
//! `Node.id` is `SHA256(fqn [|| body])` — it is *engineered* to change
//! when the FQN or body changes (see `domain::node_id`). `Node.properties`
//! is a plain `HashMap` field that travels with the node value and is
//! **not keyed on `id`**. So a doc UUID parked in `properties` is carried
//! forward across a rename as long as the rename preserves `properties`.
//! The doc UUID is the durable anchor; the engine `id` is a fingerprint
//! that may churn underneath it.
//!
//! # The structural-edge contrast (load-bearing)
//!
//! `Contains` edges *are* keyed on node `id`. So the same FQN rename that
//! churns ids ALSO breaks containment edges. This test makes that explicit:
//! doc links never break, but id-keyed edges go stale and must be relinked
//! deterministically from the FQN anchor (`rebuild_contains_edges`). That
//! is the difference between anchor-keyed linkage (resilient) and
//! id-keyed linkage (needs a relink pass).
//!
//! # Scope boundary (honest about what this is NOT)
//!
//! This exercises the **in-memory carry-forward** guarantee on the domain
//! data structures. It does NOT exercise survival across a real re-scan:
//! on a fresh scan, nodes are rebuilt from source and `properties` is
//! regenerated by the classification pass, so an externally-injected doc
//! UUID would only reappear via a durable relink store keyed on the FQN
//! anchor. That persistence layer is out of scope here by design.

use std::collections::HashMap;

use graphengine_parsing::domain::{Edge, EdgeKind, Graph, Node, NodeKind, Provenance, Range};

// ---------------------------------------------------------------------------
// In-memory external documents store (the hardcoded "Docs Object")
// ---------------------------------------------------------------------------

/// One external documentation artifact: a database id, a stable UUID, a
/// URL to the doc anywhere on the web, and a free-form keyword tag array.
#[derive(Debug, Clone, PartialEq, Eq)]
struct DocObject {
    /// Surrogate database primary key.
    db_id: u64,
    /// Stable UUID (v4). This is the value parked inside a node's
    /// `properties` — the link anchor that must survive node mutation.
    doc_id: String,
    /// Link to the doc. Can point anywhere (Confluence, Notion, GitHub).
    url: String,
    /// Keyword tags so docs can be discovered by topic.
    tags: Vec<String>,
}

/// In-memory stand-in for the external documentation system. Keyed by
/// `doc_id` so a node holding a UUID can resolve back to the full doc.
#[derive(Debug, Default)]
struct DocsStore {
    by_doc_id: HashMap<String, DocObject>,
}

impl DocsStore {
    fn new() -> Self {
        Self::default()
    }

    fn insert(&mut self, doc: DocObject) {
        self.by_doc_id.insert(doc.doc_id.clone(), doc);
    }

    fn get(&self, doc_id: &str) -> Option<&DocObject> {
        self.by_doc_id.get(doc_id)
    }

    /// Resolve a set of doc UUIDs to their full objects, in the order
    /// given. A UUID that does not resolve is an unlinkage symptom and
    /// is surfaced as a `None` the caller can assert against.
    fn resolve_all<'a>(&'a self, doc_ids: &[String]) -> Vec<Option<&'a DocObject>> {
        doc_ids.iter().map(|id| self.get(id)).collect()
    }
}

