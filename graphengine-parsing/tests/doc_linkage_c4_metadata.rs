// ---------------------------------------------------------------------------
// Node <-> doc linkage helpers (the abstraction under test)
// ---------------------------------------------------------------------------

/// Property key under which a node carries its external doc UUID links.
const DOC_LINKS_KEY: &str = "doc_links";
/// Property key carrying the node's C4 level tag (system/container/
/// component/code). GridSeak has no native C4-level field today, so the
/// fixture stamps it into the schemaless `properties` bag.
const C4_LEVEL_KEY: &str = "c4_level";

/// Attach external doc UUIDs to a node's metadata.
fn attach_docs(node: &mut Node, doc_ids: &[&str]) {
    let arr = serde_json::Value::Array(
        doc_ids
            .iter()
            .map(|d| serde_json::Value::String((*d).to_string()))
            .collect(),
    );
    node.set_property(DOC_LINKS_KEY, arr);
}

/// Read the external doc UUIDs linked to a node.
fn attached_docs(node: &Node) -> Vec<String> {
    node.properties
        .get(DOC_LINKS_KEY)
        .and_then(|v| v.as_array())
        .map(|a| {
            a.iter()
                .filter_map(|x| x.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

/// Assert, by inspecting `node.properties` **directly**, that `doc_id`
/// physically resides in the node's metadata. This deliberately does NOT
/// go through `attached_docs`; it reaches into the raw metadata bag so a
/// passing assertion means "the link is stored in the node's metadata",
/// not "a convenience reader happened to return it".
///
/// Verifies three things about the metadata field itself:
/// 1. the `doc_links` key exists in `node.properties`,
/// 2. its value is a JSON array,
/// 3. that array contains the exact `doc_id` string.
fn assert_doc_link_in_metadata(node: &Node, doc_id: &str) {
    let raw = node
        .properties
        .get(DOC_LINKS_KEY)
        .unwrap_or_else(|| panic!("node `{}` metadata has no `{DOC_LINKS_KEY}` key", node.fqn));
    let arr = raw.as_array().unwrap_or_else(|| {
        panic!(
            "`{DOC_LINKS_KEY}` in `{}` metadata is not an array",
            node.fqn
        )
    });
    let present = arr.iter().any(|v| v.as_str() == Some(doc_id));
    assert!(
        present,
        "doc id `{doc_id}` is not present in node `{}` metadata `{DOC_LINKS_KEY}`: {raw}",
        node.fqn
    );
}

/// Construct a C4-tagged container/scaffolding node (FQN-only `id`).
fn c4_node(kind: NodeKind, fqn: &str, level: &str) -> Node {
    let mut n = Node::new(kind, fqn.to_string(), loc(), Provenance::tree_sitter());
    n.set_property(C4_LEVEL_KEY, serde_json::Value::String(level.to_string()));
    n
}

fn loc() -> Range {
    Range::with_file(1, 0, 1, 0, "fixture.rs")
}

/// Rename a node to `new_fqn`, recomputing the content-addressed `id`
/// via the public constructor while preserving `properties` and trait
/// metadata. This is the honest shape of a "relink after rename" step:
/// the id churns, the doc link rides along in `properties`.
fn rename_preserving_metadata(node: &Node, new_fqn: String) -> Node {
    let mut renamed = Node::new(node.kind, new_fqn, node.location.clone(), node.provenance);
    renamed.properties = node.properties.clone();
    renamed.trait_metadata = node.trait_metadata.clone();
    renamed
}

/// Rename every node in the subtree rooted at `old_prefix` (the node
/// whose FQN == `old_prefix`, plus every descendant whose FQN starts
/// with `old_prefix::`) to live under `new_prefix`. Recomputes each
/// node's `id`; preserves each node's `properties`.
fn rename_subtree(graph: &mut Graph, old_prefix: &str, new_prefix: &str) {
    let child_prefix = format!("{old_prefix}::");
    for node in graph.nodes.iter_mut() {
        let is_in_subtree = node.fqn == old_prefix || node.fqn.starts_with(&child_prefix);
        if is_in_subtree {
            let new_fqn = node.fqn.replacen(old_prefix, new_prefix, 1);
            *node = rename_preserving_metadata(node, new_fqn);
        }
    }
}

/// Resolve the doc UUIDs a node inherits, anchored on the **FQN**: the
/// node's own links plus those of every ancestor (every node whose FQN
/// is a prefix of this node's FQN). This is "attach high, inherit low"
/// resolved through the stable FQN anchor — it keeps working after an
/// FQN rename because parent and child FQNs move together.
fn inherited_docs_by_fqn(graph: &Graph, leaf_fqn: &str) -> Vec<String> {
    let mut acc: Vec<String> = Vec::new();
    for node in &graph.nodes {
        let is_ancestor_or_self =
            leaf_fqn == node.fqn || leaf_fqn.starts_with(&format!("{}::", node.fqn));
        if is_ancestor_or_self {
            acc.extend(attached_docs(node));
        }
    }
    acc.sort();
    acc.dedup();
    acc
}

/// id-keyed parent lookup over `Contains` edges. Returns the parent node
/// id, or `None` if the edge set has no `Contains` edge pointing at
/// `child_id` (e.g. because a rename churned the id and the edges went
/// stale before a relink pass ran).
fn contains_parent_id<'a>(graph: &'a Graph, child_id: &str) -> Option<&'a str> {
    graph
        .edges
        .iter()
        .find(|e| e.to_id == child_id && e.kind == EdgeKind::Contains)
        .map(|e| e.from_id.as_str())
}

/// Strip the last `::`-separated segment to get the parent FQN.
fn parent_fqn(fqn: &str) -> Option<String> {
    fqn.rfind("::").map(|i| fqn[..i].to_string())
}

/// Rebuild every `Contains` edge from the FQN hierarchy using the
/// nodes' *current* ids. This is the deterministic relink pass that
/// repairs id-keyed structural edges after an FQN rename churns ids.
fn rebuild_contains_edges(graph: &mut Graph) {
    let id_by_fqn: HashMap<String, String> = graph
        .nodes
        .iter()
        .map(|n| (n.fqn.clone(), n.id.clone()))
        .collect();
    let mut edges = Vec::new();
    for n in &graph.nodes {
        if let Some(pf) = parent_fqn(&n.fqn) {
            if let Some(parent_id) = id_by_fqn.get(&pf) {
                edges.push(Edge::contains(
                    parent_id.clone(),
                    n.id.clone(),
                    Provenance::tree_sitter(),
                ));
            }
        }
    }
    graph.edges = edges;
}

fn node_by_fqn<'a>(graph: &'a Graph, fqn: &str) -> &'a Node {
    graph
        .nodes
        .iter()
        .find(|n| n.fqn == fqn)
        .unwrap_or_else(|| panic!("no node with fqn `{fqn}`"))
}

