/// Sanity: the hardcoded docs store resolves a UUID to its URL + tags.
#[test]
fn hardcoded_docs_store_resolves_uuid_to_link_and_tags() {
    let store = seed_docs_store();

    let doc = store
        .get(DOC_CHECKOUT_SPEC)
        .expect("checkout spec must resolve");
    assert_eq!(doc.db_id, 3);
    assert_eq!(
        doc.url,
        "https://github.com/example/ordering/blob/main/docs/checkout.md"
    );
    assert!(doc.tags.contains(&"checkout".to_string()));

    // An unknown UUID is an explicit miss, not a panic.
    assert!(store.get("00000000-0000-4000-8000-000000000000").is_none());
}

/// Core guarantee: a doc UUID in a node's metadata survives an FQN
/// mutation that churns the content-addressed `id`. The link is intact
/// (same UUID) and still resolves in the docs store afterward.
#[test]
fn doc_uuid_in_metadata_survives_fqn_mutation_with_id_churn() {
    let store = seed_docs_store();

    let mut node = c4_node(NodeKind::Function, PLACE_ORDER_FQN, "code");
    attach_docs(&mut node, &[DOC_PLACE_ORDER_CODE]);

    let id_before = node.id.clone();
    let docs_before = attached_docs(&node);
    assert_eq!(docs_before, vec![DOC_PLACE_ORDER_CODE.to_string()]);

    // The doc id physically lives in the node's metadata bag before mutation.
    assert_doc_link_in_metadata(&node, DOC_PLACE_ORDER_CODE);

    // Mutate the FQN (rename), recomputing the id.
    let renamed = rename_preserving_metadata(
        &node,
        "ordering_platform::ordering_service::checkout::submit_order".to_string(),
    );

    // The id genuinely churned...
    assert_ne!(
        renamed.id, id_before,
        "FQN rename must churn the content-addressed id"
    );
    // ...yet the doc id is STILL inside the node's metadata after mutation.
    // This is the survival assertion, checked against `properties` directly.
    assert_doc_link_in_metadata(&renamed, DOC_PLACE_ORDER_CODE);
    assert_eq!(
        attached_docs(&renamed),
        docs_before,
        "doc link must survive the rename intact"
    );
    assert!(
        store.get(&attached_docs(&renamed)[0]).is_some(),
        "surviving doc link must still resolve in the docs store"
    );
}

/// The deeply-nested case: renaming a mid-tree component cascades FQN
/// changes (and id churn) down to its deeply nested child. Doc links —
/// at every level and on the deep child — must relink: stay intact in
/// metadata, still resolve in the store, and still inherit by FQN
/// anchor. The id-keyed `Contains` edges go stale on rename and are
/// repaired by a deterministic relink pass.
#[test]
fn c4_ordering_system_relinks_after_deeply_nested_child_rename() {
    let store = seed_docs_store();
    let mut g = build_ordering_graph();

    // --- Pre-rename baseline -------------------------------------------------
    let place_order_id_before = node_by_fqn(&g, PLACE_ORDER_FQN).id.clone();
    let place_order_docs_before = attached_docs(node_by_fqn(&g, PLACE_ORDER_FQN));
    assert_eq!(
        place_order_docs_before,
        vec![DOC_PLACE_ORDER_CODE.to_string()]
    );

    // Every level's doc id physically lives in that node's metadata before
    // the rename, including the deeply nested child.
    assert_doc_link_in_metadata(node_by_fqn(&g, SYSTEM_FQN), DOC_ARCH_OVERVIEW);
    assert_doc_link_in_metadata(node_by_fqn(&g, ORDERING_FQN), DOC_ORDERING_RUNBOOK);
    assert_doc_link_in_metadata(node_by_fqn(&g, CHECKOUT_FQN), DOC_CHECKOUT_SPEC);
    assert_doc_link_in_metadata(node_by_fqn(&g, PLACE_ORDER_FQN), DOC_PLACE_ORDER_CODE);

    // The deep child inherits docs from its component, container, and
    // system ancestors via the FQN anchor.
    let inherited_before = inherited_docs_by_fqn(&g, PLACE_ORDER_FQN);
    assert_eq!(
        inherited_before,
        sorted(vec![
            DOC_ARCH_OVERVIEW,
            DOC_ORDERING_RUNBOOK,
            DOC_CHECKOUT_SPEC,
            DOC_PLACE_ORDER_CODE,
        ]),
        "deep child must inherit docs from every ancestor level"
    );

    // id-keyed containment resolves before the rename.
    let checkout_id_before = node_by_fqn(&g, CHECKOUT_FQN).id.clone();
    assert_eq!(
        contains_parent_id(&g, &place_order_id_before),
        Some(checkout_id_before.as_str()),
        "place_order's Contains parent is checkout before rename"
    );

    // --- Mutate: rename the checkout component subtree -----------------------
    // This cascades to the deeply nested child place_order.
    let new_checkout_fqn = "ordering_platform::ordering_service::order_checkout";
    let new_place_order_fqn = "ordering_platform::ordering_service::order_checkout::place_order";
    rename_subtree(&mut g, CHECKOUT_FQN, new_checkout_fqn);

    // --- Post-rename: doc links relink ---------------------------------------
    let place_order_after = node_by_fqn(&g, new_place_order_fqn);

    // The deep child's id churned because its FQN changed.
    assert_ne!(
        place_order_after.id, place_order_id_before,
        "deeply nested child id must churn when its ancestor FQN changes"
    );
    // The doc id is STILL inside the deeply nested child's metadata after the
    // cascading rename, checked against `properties` directly.
    assert_doc_link_in_metadata(place_order_after, DOC_PLACE_ORDER_CODE);
    // The renamed component itself also kept its doc id in metadata.
    assert_doc_link_in_metadata(node_by_fqn(&g, new_checkout_fqn), DOC_CHECKOUT_SPEC);
    // Its doc link is intact and still resolves.
    assert_eq!(
        attached_docs(place_order_after),
        place_order_docs_before,
        "deep child doc link must survive the cascading rename"
    );
    assert!(
        store
            .resolve_all(&attached_docs(place_order_after))
            .iter()
            .all(Option::is_some),
        "deep child doc link must still resolve in the docs store"
    );

    // FQN-anchored inheritance still resolves the full ancestor chain.
    let inherited_after = inherited_docs_by_fqn(&g, new_place_order_fqn);
    assert_eq!(
        inherited_after, inherited_before,
        "inheritance by FQN anchor must relink identically after rename"
    );

    // Every doc link in the whole graph still resolves (nothing orphaned).
    for node in &g.nodes {
        let links = attached_docs(node);
        assert!(
            store.resolve_all(&links).iter().all(Option::is_some),
            "node `{}` has an unresolved (orphaned) doc link: {:?}",
            node.fqn,
            links
        );
    }

    // --- The structural-edge contrast ---------------------------------------
    // id-keyed Contains edges went STALE on rename: the renamed child's
    // new id has no matching edge yet. This is the unlinkage that doc
    // links (anchor-keyed) avoided.
    let place_order_id_after = place_order_after.id.clone();
    assert!(
        contains_parent_id(&g, &place_order_id_after).is_none(),
        "id-keyed Contains edge must be stale after rename (pre-relink)"
    );

    // Relink structural edges deterministically from the FQN anchor.
    rebuild_contains_edges(&mut g);
    let new_checkout_id = node_by_fqn(&g, new_checkout_fqn).id.clone();
    assert_eq!(
        contains_parent_id(&g, &place_order_id_after),
        Some(new_checkout_id.as_str()),
        "Contains edge must relink child to renamed parent after rebuild"
    );
}

fn sorted(v: Vec<&str>) -> Vec<String> {
    let mut out: Vec<String> = v.into_iter().map(str::to_string).collect();
    out.sort();
    out.dedup();
    out
}
