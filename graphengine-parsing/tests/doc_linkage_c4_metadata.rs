// FQN spine for the model:
//   ordering_platform                                            (L1 System)
//   ordering_platform::ordering_service                          (L2 Container)
//   ordering_platform::ordering_service::checkout                (L3 Component)
//   ordering_platform::ordering_service::checkout::place_order   (L4 Code)
//   ordering_platform::delivery_service                          (L2 Container)
//   ordering_platform::delivery_service::dispatch                (L3 Component)
//   ordering_platform::delivery_service::dispatch::assign_driver (L4 Code)
const SYSTEM_FQN: &str = "ordering_platform";
const ORDERING_FQN: &str = "ordering_platform::ordering_service";
const CHECKOUT_FQN: &str = "ordering_platform::ordering_service::checkout";
const PLACE_ORDER_FQN: &str = "ordering_platform::ordering_service::checkout::place_order";
const DELIVERY_FQN: &str = "ordering_platform::delivery_service";
const DISPATCH_FQN: &str = "ordering_platform::delivery_service::dispatch";
const ASSIGN_DRIVER_FQN: &str = "ordering_platform::delivery_service::dispatch::assign_driver";

/// Build the C4 ordering/delivery graph with docs attached across
/// levels: System → arch overview, ordering Container → runbook,
/// checkout Component → spec, place_order Code → code doc.
fn build_ordering_graph() -> Graph {
    let mut g = Graph::new();

    let mut system = c4_node(NodeKind::Project, SYSTEM_FQN, "system");
    attach_docs(&mut system, &[DOC_ARCH_OVERVIEW]);

    let mut ordering = c4_node(NodeKind::Module, ORDERING_FQN, "container");
    attach_docs(&mut ordering, &[DOC_ORDERING_RUNBOOK]);

    let mut checkout = c4_node(NodeKind::Module, CHECKOUT_FQN, "component");
    attach_docs(&mut checkout, &[DOC_CHECKOUT_SPEC]);

    let mut place_order = c4_node(NodeKind::Function, PLACE_ORDER_FQN, "code");
    attach_docs(&mut place_order, &[DOC_PLACE_ORDER_CODE]);

    let delivery = c4_node(NodeKind::Module, DELIVERY_FQN, "container");
    let dispatch = c4_node(NodeKind::Module, DISPATCH_FQN, "component");
    let assign_driver = c4_node(NodeKind::Function, ASSIGN_DRIVER_FQN, "code");

    for n in [
        system,
        ordering,
        checkout,
        place_order,
        delivery,
        dispatch,
        assign_driver,
    ] {
        g.add_node(n);
    }

    rebuild_contains_edges(&mut g);
    g
}

